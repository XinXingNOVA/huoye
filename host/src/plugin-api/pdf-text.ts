/**
 * 简化字形的部首（CJK 部首补充区）：Unicode 没有给它们对应的普通汉字，NFKC 换不掉。
 * 有的 PDF 字体拿它们当字用（"页"抽出来是"⻚"），按 Unicode 的部首名称对上常用的字。J- 开头的是日文的简化字形。
 */
const RADICALS: Record<string, string> = {
  '⺦': '丬', '⺰': '纟', '⻅': '见', '⻆': '角', '⻈': '讠', '⻉': '贝', '⻋': '车', '⻌': '辶', '⻐': '钅',
  '⻓': '长', '⻔': '门', '⻙': '韦', '⻚': '页', '⻛': '风', '⻜': '飞', '⻠': '饣', '⻢': '马', '⻥': '鱼',
  '⻦': '鸟', '⻧': '卤', '⻨': '麦', '⻩': '黄', '⻪': '黾', '⻫': '斉', '⻬': '齐', '⻭': '歯', '⻮': '齿',
  '⻯': '竜', '⻰': '龙', '⻲': '亀'
}

/** 核心抽文和界面摘录使用同一份汉字规范化规则。 */
export const normalizePdfText = (text: string) => text.replace(/[\u2E80-\u2FDF\uF900-\uFAFF]/g, (c) => RADICALS[c] ?? c.normalize('NFKC'))
